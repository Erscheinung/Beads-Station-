import { beforeEach, describe, expect, it, vi } from 'vitest'
import { dispatchCommand, eventBinding, getBinding, LEADER_SHORTCUTS, matchedCommand, resetBindings, setBinding } from './commands'

describe('command bindings', () => {
  beforeEach(resetBindings)
  it('rebinds the action and releases its old shortcut', () => {
    expect(setBinding('palette', 'Mod+Shift+J')).toBeNull()
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'k', metaKey: true }))).toBeUndefined()
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'J', metaKey: true, shiftKey: true }))).toBe('palette')
    expect(JSON.parse(localStorage.getItem('beads-station.command-bindings.v1')!).palette).toBe('Mod+Shift+J')
  })
  it('rejects conflicts and protects editing, pane leader and Escape', () => {
    expect(setBinding('workspace', 'Mod+K')).toContain('Command palette')
    expect(setBinding('workspace', 'Mod+P')).toContain('Reserved')
    expect(setBinding('workspace', 'Mod+C')).toContain('Reserved')
    expect(setBinding('workspace', 'Mod+Escape')).toBeTruthy()
    expect(eventBinding(new KeyboardEvent('keydown', { key: 'Escape' }))).toBe('')
    expect(getBinding('workspace')).toBe('')
  })
  it('exposes fullscreen as a safe configurable command and keeps leader help truthful', () => {
    expect(getBinding('fullscreen')).toBe('Mod+Shift+Enter')
    expect(setBinding('workspace', 'Mod+Shift+Enter')).toContain('Fullscreen terminal focus')
    expect(setBinding('fullscreen', 'Mod+Shift+F')).toBeNull()
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'F', metaKey: true, shiftKey: true }))).toBe('fullscreen')
    expect(LEADER_SHORTCUTS.global.find(h => h.key === 'p')?.label).toBe('Cycle project')
    expect(LEADER_SHORTCUTS.terminal.find(h => h.key === 'e')?.label).toBe('Open files explorer')

    const listener = vi.fn()
    window.addEventListener('terminal:focus-toggle', listener)
    dispatchCommand('fullscreen')
    window.removeEventListener('terminal:focus-toggle', listener)
    expect(listener).toHaveBeenCalledTimes(1)
  })
  it('exposes directional focus and resize commands with modifier-only defaults', () => {
    expect(getBinding('focusLeft')).toBe('Mod+Shift+ArrowLeft')
    expect(getBinding('focusRight')).toBe('Mod+Shift+ArrowRight')
    expect(getBinding('focusUp')).toBe('Mod+Shift+ArrowUp')
    expect(getBinding('focusDown')).toBe('Mod+Shift+ArrowDown')
    expect(getBinding('resizeLeft')).toBe('Ctrl+Shift+ArrowLeft')
    expect(getBinding('resizeRight')).toBe('Ctrl+Shift+ArrowRight')
    expect(getBinding('resizeUp')).toBe('Ctrl+Shift+ArrowUp')
    expect(getBinding('resizeDown')).toBe('Ctrl+Shift+ArrowDown')
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'ArrowLeft', metaKey: true, shiftKey: true }), true)).toBe('focusLeft')
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'ArrowLeft', ctrlKey: true, shiftKey: true }), true)).toBe('resizeLeft')
  })
  it('leaves composition and unbound keys alone', () => {
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'k', metaKey: true, isComposing: true }))).toBeUndefined()
    setBinding('palette', '')
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'k', ctrlKey: true }))).toBeUndefined()
  })
  it('provides conflict-safe workspace and terminal navigation defaults', () => {
    expect(getBinding('workspacePrevious')).toBe('Mod+[')
    expect(getBinding('workspaceNext')).toBe('Mod+]')
    expect(getBinding('terminalPrevious')).toBe('Mod+Shift+[')
    expect(getBinding('terminalNext')).toBe('Mod+Shift+]')
    expect(getBinding('workspaceSelect1')).toBe('Mod+1')
    expect(getBinding('terminalSelect9')).toBe('Ctrl+Shift+9')
    expect(getBinding('initializeBeads')).toBe('')
    expect(setBinding('workspaceNext', 'Mod+K')).toContain('Command palette')
  })

  it('keeps a user shortcut when an update adds a command with the same default', async () => {
    // Saved by an older version: no entry for the newer notificationJump command.
    localStorage.setItem('beads-station.command-bindings.v1', JSON.stringify({ palette: 'Mod+K', workspace: 'Mod+Shift+U' }))
    localStorage.setItem('beads-station.recipe-bindings.v1', JSON.stringify({ r1: { label: 'Review', binding: 'Mod+Shift+Y' } }))
    vi.resetModules()
    const upgraded = await import('./commands')
    expect(upgraded.getBinding('workspace')).toBe('Mod+Shift+U')
    expect(upgraded.getBinding('notificationJump')).toBe('')
    expect(upgraded.matchedCommand(new KeyboardEvent('keydown', { key: 'U', metaKey: true, shiftKey: true }))).toBe('workspace')
    expect(upgraded.getRecipeBinding('r1')).toBe('Mod+Shift+Y')
    localStorage.clear()
    vi.resetModules()
    const fresh = await import('./commands')
    expect(fresh.getBinding('notificationJump')).toBe('Mod+Shift+U')
  })
  it('accepts Tab chords and spells macOS Control chords as Ctrl', () => {
    const ctrlShiftTab = new KeyboardEvent('keydown', { key: 'Tab', ctrlKey: true, shiftKey: true })
    expect(eventBinding(ctrlShiftTab, true)).toBe('Ctrl+Shift+Tab')
    expect(eventBinding(ctrlShiftTab, false)).toBe('Mod+Shift+Tab')
    expect(setBinding('terminalPrevious', 'Ctrl+Shift+Tab')).toBeNull()
    expect(setBinding('terminalNext', 'Ctrl+Tab')).toBeNull()
    expect(matchedCommand(ctrlShiftTab, true)).toBe('terminalPrevious')
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'Tab', ctrlKey: true }), true)).toBe('terminalNext')
  })
  it('leaves Control+key to the shell on macOS but keeps modified Control chords working', () => {
    expect(setBinding('workspace', 'Ctrl+K')).toContain('shell')
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'k', ctrlKey: true }), true)).toBeUndefined()
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'k', metaKey: true }), true)).toBe('palette')
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'k', ctrlKey: true }), false)).toBe('palette')
    expect(matchedCommand(new KeyboardEvent('keydown', { key: 'Enter', ctrlKey: true, shiftKey: true }), true)).toBe('fullscreen')
  })
})

describe('keys whose character changes with a modifier', () => {
  const key = (init: KeyboardEventInit) => new KeyboardEvent('keydown', init)

  it('names the key, not the character Shift or Option produces', async () => {
    const { eventBinding } = await import('./commands')
    expect(eventBinding(key({ key: '!', code: 'Digit1', metaKey: true, shiftKey: true }), true)).toBe('Mod+Shift+1')
    expect(eventBinding(key({ key: '{', code: 'BracketLeft', metaKey: true, shiftKey: true }), true)).toBe('Mod+Shift+[')
    expect(eventBinding(key({ key: '“', code: 'BracketLeft', metaKey: true, altKey: true }), true)).toBe('Mod+Alt+[')
    expect(eventBinding(key({ key: 'å', code: 'KeyA', metaKey: true, altKey: true }), true)).toBe('Mod+Alt+A')
    expect(eventBinding(key({ key: 'k', code: 'KeyK', metaKey: true }), true)).toBe('Mod+K')
  })

  it('moves a saved retired default to the new one and keeps a real choice', async () => {
    vi.resetModules()
    localStorage.setItem('beads-station.command-bindings.v1', JSON.stringify({ focusLeft: 'Mod+Alt+ArrowLeft', focusRight: 'Mod+Alt+L', workspaceSelect1: 'Mod+Alt+1' }))
    const { getBinding } = await import('./commands')
    expect(getBinding('focusLeft')).toBe('Mod+Shift+ArrowLeft')
    expect(getBinding('focusRight')).toBe('Mod+Alt+L')
    expect(getBinding('workspaceSelect1')).toBe('Mod+1')
    localStorage.removeItem('beads-station.command-bindings.v1')
    vi.resetModules()
  })
})
