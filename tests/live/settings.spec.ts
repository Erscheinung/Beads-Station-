test('view themes stay independent across switching and reload', async ({ page }) => {
  await page.keyboard.press('Meta+,')
  await page.getByRole('button', { name: 'Appearance', exact: true }).click()
  await page.getByRole('button', { name: 'fahrenheit', exact: false }).click()
  await page.getByLabel('Theme for view', { exact: true }).selectOption('designer')
  await page.getByRole('button', { name: 'one light', exact: false }).click()
  await expect(page.locator('.bs-settings')).toHaveCSS('background-color', 'rgb(0, 0, 0)')
  await page.getByRole('button', { name: 'Close settings' }).click()
  await page.getByRole('button', { name: 'Designer', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).__bsThemePaletteId)).toBe('one-light')
  await page.reload()
  await expect.poll(() => page.evaluate(() => (window as any).__bsThemePaletteId)).toBe('one-light')
  await page.getByRole('button', { name: 'Terminal skin', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).__bsThemePaletteId)).toBe('fahrenheit')
  await page.keyboard.press('Meta+,')
  await page.getByLabel('Search settings', { exact: true }).fill('scrollback')
  await page.getByRole('button', { name: 'Terminal', exact: true }).click()
  await page.getByLabel('Cursor shape', { exact: true }).selectOption('bar')
  await page.getByLabel('Blink cursor', { exact: true }).uncheck()
  await page.getByLabel('Scrollback lines', { exact: false }).fill('5000')
  await page.screenshot({ path: 'test-results/settings-terminal.png' })
  await page.reload()
  await page.getByTitle('Open settings', { exact: true }).click()
  await page.getByRole('button', { name: 'Terminal', exact: true }).click()
  await expect(page.getByLabel('Cursor shape', { exact: true })).toHaveValue('bar')
  await expect(page.getByLabel('Blink cursor', { exact: true })).not.toBeChecked()
  await expect(page.getByLabel('Scrollback lines', { exact: false })).toHaveValue('5000')
})

test('visible close and unsplit keep surviving terminal sessions', async ({ page }) => {
  const calls = (cmd: string) => page.evaluate(cmd => (window as any).__bsInvokeLog.filter((e: any) => e.cmd === cmd), cmd)
  await expect.poll(async () => (await calls('pty_spawn')).length).toBe(1)
  await page.getByRole('button', { name: 'Split right', exact: true }).click()
  await page.getByRole('button', { name: 'Split down', exact: true }).click()
  await expect.poll(async () => (await calls('pty_spawn')).length).toBe(3)
  await page.getByRole('button', { name: 'Zoom pane', exact: true }).click()
  await page.getByRole('button', { name: 'Close pane', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.locator('[data-terminal-pane]')).toHaveCount(2)
  await expect(page.locator('[data-terminal-pane]').first()).toBeVisible()
  await expect.poll(async () => (await calls('pty_kill')).length).toBe(1)
  const kills = (await calls('pty_kill')).length
  await page.getByRole('button', { name: 'Unsplit to tabs', exact: true }).click()
  await expect(page.locator('[data-terminal-pane]')).toHaveCount(1)
  await expect(page.getByRole('tablist', { name: 'Terminal tabs' }).getByRole('tab')).toHaveCount(2)
  await page.getByRole('tablist', { name: 'Terminal tabs' }).getByRole('tab').nth(1).click()
  await expect(page.locator('[data-terminal-pane]')).toBeVisible()
  expect((await calls('pty_spawn')).length).toBe(3)
  expect((await calls('pty_kill')).length).toBe(kills)
})
